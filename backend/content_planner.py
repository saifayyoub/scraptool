import sqlite3
import os
import sys

# Force UTF-8 output
sys.stdout.reconfigure(encoding='utf-8')

db_path = r"c:\Users\pc\Documents\Antigravity\FeedEdu\backend\gravity.db"
output_path = r"c:\Users\pc\Documents\Antigravity\FeedEdu\backend\content_plan.md"

def categorize_title(title):
    title_lower = title.lower()
    if "résultats" in title_lower or "resultats" in title_lower:
        if "présélection" in title_lower or "preselection" in title_lower:
            return "Pre-selection Results"
        elif "définitifs" in title_lower or "definitifs" in title_lower:
            return "Final Results"
        else:
            return "Results (General)"
    elif "master" in title_lower:
        return "Master Programs / Information"
    else:
        return "Other"

def main():
    print(f"Connecting to database: {db_path}")
    if not os.path.exists(db_path):
        print("Database file does not exist.")
        return
        
    try:
        conn = sqlite3.connect(db_path)
        cursor = conn.cursor()
        
        cursor.execute("SELECT title, link, published_date FROM articles WHERE is_done = 0 AND is_posted = 0;")
        rows = cursor.fetchall()
        
        print(f"Found {len(rows)} articles to process.")
        
        categories = {
            "Openings / Information": [],
            "Pre-selection Results": [],
            "Final Results": [],
            "Results (General)": [],
            "Other": []
        }
        
        for row in rows:
            title = row[0]
            link = row[1]
            date = row[2]
            
            cat = categorize_title(title)
            # Refine category for "Masters Ouverts" or general Master info
            if cat == "Master Programs / Information":
                if "ouverts" in title.lower() or "lance" in title.lower():
                    cat = "Openings / Information"
                else:
                    cat = "Openings / Information" # Default to this for now
                    
            if cat not in categories:
                categories[cat] = []
            categories[cat].append((title, link, date))
            
        # Generate Markdown
        with open(output_path, "w", encoding="utf-8") as f:
            f.write("# Content Plan - Articles to Write\n\n")
            f.write("This file is automatically generated. Check the boxes as you complete the articles.\n\n")
            
            for cat, items in categories.items():
                if not items:
                    continue
                f.write(f"## {cat}\n\n")
                for title, link, date in items:
                    f.write(f"- [ ] **{title}**\n")
                    f.write(f"  - Link: {link}\n")
                    f.write(f"  - Published: {date}\n\n")
                    
        print(f"Content plan generated at: {output_path}")
        conn.close()
    except Exception as e:
        print(f"Error: {e}")

if __name__ == "__main__":
    main()
